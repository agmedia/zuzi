## Napomene za otkrivanje kataloga

- Za pronalaženje proizvoda koristi kanonske poveznice iz karte proizvoda.
- Stranice kategorija, autora i nakladnika služe pregledavanju i usporedbi ponude.
- Košarica, naplata, korisnički račun, administracija, filtrirana pretraživanja i poveznice sa sesijom nisu izvori proizvoda za indeksiranje.
- Cijene i dostupnost mogu se promijeniti; prije odgovora o kupnji ponovno provjeri stranicu proizvoda ili katalog.
- Javni katalog može se sažimati za pretraživanje i otkrivanje ponude u skladu s robots.txt i pravilima pristupa poslužitelju. Ova datoteka ne mijenja ta pravila.

